def load_src_audio(path):
    raw = run(["ffmpeg", "-v", "error", "-i", path, "-vn", "-ac", "2", "-ar", str(SR),
               "-f", "f32le", "-"], capture_output=True).stdout
    return np.frombuffer(raw, np.float32).reshape(-1, 2).astype(np.float64)


def seg_map(seg, t):
    ks = seg["keys"]
    return np.interp(t, [k[0] for k in ks], [k[1] for k in ks])


def game_audio(srcs):
    out = np.zeros((int(TOTAL * SR), 2))
    for seg in SEGMENTS:
        if seg.get("endcard"):
            continue
        a0, a1 = seg["keys"][0][0], seg["keys"][-1][0]
        i0, i1 = int(a0 * SR), int(a1 * SR)
        t = np.arange(i0, i1) / SR
        st = seg_map(seg, t)
        src = srcs[seg["src"]]
        idx = st * SR
        y = np.stack([np.interp(idx, np.arange(len(src)), src[:, c]) for c in range(2)], 1)
        # gain: inside narration-free windows only, muted on freeze frames
        g = np.zeros(len(t))
        for w0, w1 in GAME_AUDIO_WINDOWS[seg["src"]]:
            g = np.maximum(g, np.clip(np.minimum(st - w0, w1 - st) / 0.06, 0, 1))
        rate = np.gradient(st) * SR
        g *= np.clip(rate / 0.3, 0, 1)
        n = len(t)
        f = min(int(0.012 * SR), n // 2)
        g[:f] *= np.linspace(0, 1, f)
        g[-f:] *= np.linspace(1, 0, f)
        out[i0:i1] += y * g[:, None]
    return out


def envelope(x, att=0.03, rel=0.3):
    lvl = np.abs(x).max(1) if x.ndim == 2 else np.abs(x)
    ea, er = math.exp(-1 / (att * SR)), math.exp(-1 / (rel * SR))
    env = np.zeros_like(lvl)
    e = 0.0
    # decimated follower for speed
    hop = 64
    for i in range(0, len(lvl), hop):
        v = lvl[i:i + hop].max()
        c = ea ** hop if v > e else er ** hop
        e = c * e + (1 - c) * v
        env[i:i + hop] = e
    return env


def ffmpeg_write_wav(x, path, codec="pcm_s24le"):
    x = np.ascontiguousarray(x.astype(np.float32))
    run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", str(x.shape[1] if x.ndim == 2 else 1),
         "-i", "-", "-c:a", codec, path], input=x.tobytes())


