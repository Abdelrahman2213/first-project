def band_sweep(dur, f0, f1, env, width=(0.6, 1.8), hop=1024):
    """Stereo noise through a band-pass whose centre glides f0 -> f1 (log)."""
    n = int(dur * SR)
    p = np.arange(n) / n
    noise = RNG.standard_normal((n, 2))
    out = np.zeros_like(noise)
    for i in range(0, n, hop):
        fc = f0 * (f1 / f0) ** p[i]
        seg = noise[max(0, i - 512): i + hop]
        y = sos_filter(seg, "bandpass", [max(20, fc * width[0]), min(fc * width[1], 20000)])
        out[i: i + hop] = y[-len(out[i: i + hop]):]
    return out * env(p)[:, None]


def swish(dur=0.2):
    return band_sweep(dur, 1500, 9000, lambda p: np.sin(np.pi * p) ** 2) * 0.8


def heartbeat(strength=1.0):
    t = t_arr(0.6)
    x = np.zeros(len(t))
    for d, a in ((0.0, 1.0), (0.17, 0.7)):
        tt = np.clip(t - d, 0, None)
        f = 42 + 45 * np.exp(-tt / 0.03)
        x += (t >= d) * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-tt / 0.08) * a
    return np.tanh(2 * x) * 0.9 * strength


def braam(dur=2.2, f=55.0):
    """Low cinematic 'braam' hit: detuned saw cluster through an opening/closing low-pass."""
    t = t_arr(dur)
    x = sum(signal.sawtooth(2 * np.pi * ff * t + RNG.uniform(0, 6))
            for ff in (f, f * 1.007, f * 0.993, 2 * f * 1.003, 2 * f * 0.996))
    x = np.tanh(1.8 * x / 3)
    out = np.zeros(len(t))
    hop = 1024
    for i in range(0, len(t), hop):
        fc = 250 + 2200 * math.exp(-t[i] / 0.35) * min(t[i] / 0.03, 1)
        y = sos_filter(x[max(0, i - 1024): i + hop], "lowpass", fc)
        out[i: i + hop] = y[-len(out[i: i + hop]):]
    return out * np.minimum(t / 0.025, 1) * np.exp(-t / 0.9) * 0.9


def hit_confirm():
    """Bright metallic 'kill confirmed' ping."""
    t = t_arr(0.6)
    x = sum(np.sin(2 * np.pi * f * t) * np.exp(-t / d) * a
            for f, d, a in ((2350, 0.22, 0.5), (3525, 0.15, 0.35), (4700, 0.1, 0.25), (1175, 0.3, 0.25)))
    click = sos_filter(RNG.standard_normal(len(t)), "highpass", 3000) * np.exp(-t / 0.004) * 0.4
    return (x + click) * 0.6


def tinnitus(dur, f=3700):
    t = t_arr(dur)
    return np.sin(2 * np.pi * f * t) * np.minimum(t / 0.08, 1) * np.exp(-t / (dur * 0.45)) * 0.12


def debris(dur=1.8, count=55):
    n = int(dur * SR)
    x = np.zeros(n)
    for _ in range(count):
        t0 = RNG.exponential(dur * 0.25)
        if t0 > dur - 0.05:
            continue
        L = int(RNG.uniform(0.004, 0.03) * SR)
        i0 = int(t0 * SR)
        burst = RNG.standard_normal(L) * np.exp(-np.arange(L) / (L / 4))
        x[i0:i0 + L] += burst[: n - i0] * math.exp(-t0 / (dur * 0.4)) * RNG.uniform(0.3, 1)
    return sos_filter(x, "bandpass", [800, 7000]) * 0.7


def metal_click(f1=1900, f2=3100):
    t = t_arr(0.12)
    n = sos_filter(RNG.standard_normal(len(t)), "bandpass", [1500, 8000]) * np.exp(-t / 0.006)
    r = (np.sin(2 * np.pi * f1 * t) * 0.5 + np.sin(2 * np.pi * f2 * t) * 0.35) * np.exp(-t / 0.035)
    return (n * 0.8 + r) * 0.6


def weapon_rack():
    x = np.zeros(int(0.35 * SR))
    a, b = metal_click(), metal_click(1250, 2150)
    x[:len(a)] += a
    i = int(0.15 * SR)
    x[i:i + len(b)] += b * 1.1
    return x


def scope_whirr():
    t = t_arr(0.3)
    p = t / 0.3
    servo = sos_filter(signal.square(2 * np.pi * np.cumsum(500 + 900 * p) / SR) * 0.15, "bandpass", [400, 3000])
    air = sos_filter(RNG.standard_normal(len(t)), "bandpass", [1000, 5000]) * 0.2
    x = (servo + air) * np.sin(np.pi * p) ** 0.8
    c = metal_click(2600, 4100)
    x[-len(c):] += c * 0.8          # lock-on click
    return x


def glitch_sparkle(dur, density=70):
    """Digital materialise: random bit-crushed blips + sample-and-hold noise."""
    n = int(dur * SR)
    out = np.zeros((n, 2))
    for _ in range(int(density * dur)):
        t0 = RNG.uniform(0, max(dur - 0.07, 0.01))
        L = int(RNG.uniform(0.012, 0.05) * SR)
        tt = np.arange(L) / SR
        s = np.sin(2 * np.pi * RNG.uniform(1800, 7500) * tt) * np.exp(-tt / (L / SR / 3))
        if RNG.random() < 0.35:
            s = np.round(s * 3) / 3
        pan = RNG.uniform(-0.8, 0.8)
        i0 = int(t0 * SR)
        seg = out[i0:i0 + L]
        seg[:, 0] += s[:len(seg)] * math.cos((pan + 1) * math.pi / 4)
        seg[:, 1] += s[:len(seg)] * math.sin((pan + 1) * math.pi / 4)
    sh = sos_filter(np.repeat(RNG.uniform(-1, 1, n // 24 + 1), 24)[:n], "highpass", 2000) * 0.15
    gate = np.repeat(RNG.random(n // 2400 + 1), 2400)[:n] > 0.55
    out += (sh * gate)[:, None]
    p = np.arange(n) / n
    return out * (np.minimum(p / 0.1, 1) * (1 - p) ** 0.7)[:, None] * 0.35


def shimmer(dur=1.2):
    n = int(dur * SR)
    t = np.arange(n) / SR
    x = sos_filter(RNG.standard_normal((n, 2)), "bandpass", [6000, 14000])
    out = x * (np.minimum(t / 0.05, 1) * np.exp(-t / 0.35))[:, None] * 0.35
    sp = glitch_sparkle(dur * 0.8, 40)
    out[:len(sp)] += sp * 1.2
    return out


