def read_wav_mono(path):
    with wave.open(path) as w:
        sr = w.getframerate()
        a = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768
        if w.getnchannels() == 2:
            a = a.reshape(-1, 2).mean(1)
    return a, sr


def trim_silence(a, thr=0.012, pad_s=0.03):
    idx = np.where(np.abs(a) > thr)[0]
    if not len(idx):
        return a
    p = int(pad_s * SR)
    return a[max(0, idx[0] - p): idx[-1] + p]


def compress(x, thr_db=-20, ratio=3.0, att=0.004, rel=0.09, makeup_db=0):
    """Feed-forward peak compressor (one-pole release follower)."""
    thr = 10 ** (thr_db / 20)
    er = math.exp(-1 / (rel * SR))
    env = signal.lfilter([1 - er], [1, -er], np.abs(x))
    env = np.maximum(env, 1e-9)
    gain = np.where(env > thr, (thr * (env / thr) ** (1 / ratio)) / env, 1.0)
    return x * gain * 10 ** (makeup_db / 20)


def deess(x, lo=5000, hi=10000, thr_db=-30, ratio=4.0):
    band = sos_filter(x, "bandpass", [lo, hi], 2)
    rest = x - band
    return rest + compress(band, thr_db, ratio, 0.001, 0.04)


def process_vo(a):
    a = sos_filter(a, "highpass", 85)
    a = peaking(a, 220, -2.0, 1.0)       # clear mud
    a = peaking(a, 3200, 3.0, 0.9)       # presence
    a = peaking(a, 110, 1.5, 0.8)        # a bit of chest
    a = compress(a, -22, 3.0, 0.004, 0.1)
    a = deess(a)
    a = np.tanh(a * 1.3) / np.tanh(1.3)  # gentle saturation
    return a / (np.abs(a).max() + 1e-9) * 0.89


def synth_vo(voices_dir, work):
    from piper import PiperVoice, SynthesisConfig
    model = os.path.join(voices_dir, "en_US-joe-medium.onnx")
    voice = PiperVoice.load(model)
    vo_dir = os.path.join(work, "vo")
    os.makedirs(vo_dir, exist_ok=True)
    track = np.zeros(int(TOTAL * SR))
    placed = []
    prev_end = 0.0
    for i, (t0, text, ls) in enumerate(VO_LINES):
        p = os.path.join(vo_dir, f"line_{i:02d}.wav")
        with wave.open(p, "wb") as w:
            voice.synthesize_wav(text, w, syn_config=SynthesisConfig(
                length_scale=ls, noise_scale=0.6, noise_w_scale=0.7))
        a, sr = read_wav_mono(p)
        a = signal.resample_poly(a, SR // math.gcd(SR, sr), sr // math.gcd(SR, sr))
        a = trim_silence(a)
        a = process_vo(a)
        dur = len(a) / SR
        if t0 < prev_end + 0.05:
            log(f"  WARN VO line {i} overlaps previous ({t0:.2f} < {prev_end:.2f}), shifting")
            t0 = prev_end + 0.05
        i0 = int(t0 * SR)
        track[i0:i0 + len(a)] += a[: len(track) - i0]
        placed.append(dict(start=round(t0, 3), end=round(t0 + dur, 3), text=text))
        prev_end = t0 + dur
        log(f"  VO {t0:6.2f}-{t0 + dur:6.2f}  {text}")
    # subtle room
    st = reverb(track, make_ir(0.6, 0.12, seed=3, lp=7000), 0.07)
    return st, placed


