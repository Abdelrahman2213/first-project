def font(path, size):
    return ImageFont.truetype(path, size)


def text_width(fnt, text, tracking):
    w = 0
    for i, ch in enumerate(text):
        w += fnt.getlength(ch) + (tracking if i < len(text) - 1 else 0)
    return w


def render_lines(lines, max_w=920, gap=0.02, glow=True):
    """lines: [(text, rgb, size, font_path, tracking)] -> BGRA numpy image"""
    rendered = []
    for text, rgb, size, fpath, tr in lines:
        fnt = font(fpath, size)
        tw = text_width(fnt, text, tr)
        if tw > max_w:  # auto-fit
            size = int(size * max_w / tw)
            fnt = font(fpath, size)
            tw = text_width(fnt, text, tr)
        asc, desc = fnt.getmetrics()
        rendered.append((text, rgb, size, fnt, tr, tw, asc + desc))
    pad = 60
    bw = int(max(r[5] for r in rendered)) + pad * 2
    bh = int(sum(r[6] for r in rendered) * (1 + gap)) + pad * 2
    mask_fill = Image.new("RGBA", (bw, bh), (0, 0, 0, 0))
    mask_all = Image.new("L", (bw, bh), 0)
    d = ImageDraw.Draw(mask_fill)
    dm = ImageDraw.Draw(mask_all)
    y = pad
    for text, rgb, size, fnt, tr, tw, lh in rendered:
        x = (bw - tw) / 2
        for ch in text:
            d.text((x, y), ch, font=fnt, fill=rgb + (255,))
            dm.text((x, y), ch, font=fnt, fill=255)
            x += fnt.getlength(ch) + tr
        y += lh * (1 + gap)
    base = Image.new("RGBA", (bw, bh), (0, 0, 0, 0))
    # drop shadow
    sh = mask_all.filter(ImageFilter.GaussianBlur(10))
    shadow = Image.new("RGBA", (bw, bh), (0, 0, 0, 0))
    shadow.putalpha(sh.point(lambda v: int(v * 0.85)))
    base = Image.alpha_composite(base, shadow)
    if glow:
        g = mask_all.filter(ImageFilter.GaussianBlur(18))
        glow_l = Image.new("RGBA", (bw, bh), CYAN_RGB + (0,))
        glow_l.putalpha(g.point(lambda v: int(v * 0.55)))
        base = Image.alpha_composite(base, glow_l)
    base = Image.alpha_composite(base, mask_fill)
    arr = np.array(base)
    return arr[..., [2, 1, 0, 3]].copy()  # RGBA -> BGRA


def gradient_band(h=760, strength=0.62):
    y = np.linspace(-1, 1, h)
    a = (1 - np.abs(y) ** 2) * strength
    img = np.zeros((h, W, 4), np.uint8)
    img[..., 3] = (a[:, None] * 255).astype(np.uint8)
    img[..., :3] = (8, 6, 4)
    return img


def rounded_panel(w, h, r, fill_rgba, border_rgb=None, bw=4, glow=True):
    pad = 50
    im = Image.new("RGBA", (w + 2 * pad, h + 2 * pad), (0, 0, 0, 0))
    if glow and border_rgb:
        g = Image.new("L", im.size, 0)
        ImageDraw.Draw(g).rounded_rectangle([pad, pad, pad + w, pad + h], r, outline=255, width=bw + 6)
        g = g.filter(ImageFilter.GaussianBlur(16))
        gl = Image.new("RGBA", im.size, border_rgb + (0,))
        gl.putalpha(g.point(lambda v: int(v * 0.8)))
        im = Image.alpha_composite(im, gl)
    layer = Image.new("RGBA", im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    d.rounded_rectangle([pad, pad, pad + w, pad + h], r, fill=fill_rgba,
                        outline=(border_rgb + (255,)) if border_rgb else None, width=bw)
    im = Image.alpha_composite(im, layer)
    arr = np.array(im)
    return arr[..., [2, 1, 0, 3]].copy()


def hline(w, thickness=4, rgb=CYAN_RGB):
    pad = 30
    im = Image.new("RGBA", (w + 2 * pad, thickness + 2 * pad), (0, 0, 0, 0))
    g = Image.new("L", im.size, 0)
    ImageDraw.Draw(g).rectangle([pad, pad, pad + w, pad + thickness], fill=255)
    gb = g.filter(ImageFilter.GaussianBlur(8))
    gl = Image.new("RGBA", im.size, rgb + (0,))
    gl.putalpha(gb)
    im = Image.alpha_composite(im, gl)
    solid = Image.new("RGBA", im.size, rgb + (0,))
    solid.putalpha(g)
    im = Image.alpha_composite(im, solid)
    arr = np.array(im)
    return arr[..., [2, 1, 0, 3]].copy()


def ease_out(x):
    x = min(max(x, 0.0), 1.0)
    return 1 - (1 - x) ** 3


def ease_out_back(x, s=1.6):
    x = min(max(x, 0.0), 1.0) - 1
    return 1 + (s + 1) * x ** 3 + s * x ** 2


class Overlay:
    def __init__(self, img, cx, cy, t0, t1, anim="slam", scale0=1.35, fade_out=0.12,
                 wipe=0.0, delay_alpha=0.06, pulse=False, slide=0, scale_x_anim=False):
        self.img, self.cx, self.cy, self.t0, self.t1 = img, cx, cy, t0, t1
        self.anim, self.scale0, self.fade_out, self.wipe = anim, scale0, fade_out, wipe
        self.delay_alpha, self.pulse, self.slide, self.scale_x_anim = delay_alpha, pulse, slide, scale_x_anim

    def draw(self, frame, t):
        if not (self.t0 <= t < self.t1):
            return
        u, r = t - self.t0, self.t1 - t
        alpha = min(u / self.delay_alpha, 1.0) if self.delay_alpha > 0 else 1.0
        if self.fade_out > 0:
            alpha *= min(r / self.fade_out, 1.0)
        sx = sy = 1.0
        dx = 0.0
        if self.anim == "slam":
            s = 1 + (self.scale0 - 1) * (1 - ease_out(u / 0.16))
            sx = sy = s
        elif self.anim == "pop":
            s = 0.6 + 0.4 * ease_out_back(u / 0.28)
            sx = sy = s
        elif self.anim == "slide":
            dx = self.slide * (1 - ease_out(u / 0.3))
        if self.scale_x_anim:
            sx = max(0.02, ease_out(u / 0.4))
            sy = 1.0
        if r < self.fade_out:  # tiny push on exit
            k = 1 + 0.06 * (1 - r / self.fade_out)
            sx *= k
            sy *= k
        if self.pulse:
            ph = ((t - self.t0) % BEAT) / BEAT
            k = 1 + 0.035 * math.exp(-ph * 6)
            sx *= k
            sy *= k
        img = self.img
        if self.wipe > 0:
            frac = ease_out(u / self.wipe)
            cut = int(img.shape[1] * frac)
            img = img.copy()
            img[:, cut:, 3] = 0
        if abs(sx - 1) > 1e-3 or abs(sy - 1) > 1e-3:
            nw, nh = max(2, int(img.shape[1] * sx)), max(2, int(img.shape[0] * sy))
            img = cv2.resize(img, (nw, nh), interpolation=cv2.INTER_LINEAR)
        blit(frame, img, self.cx + dx, self.cy, alpha)


def blit(frame, img, cx, cy, alpha=1.0):
    h, w = img.shape[:2]
    x0, y0 = int(round(cx - w / 2)), int(round(cy - h / 2))
    fx0, fy0 = max(0, x0), max(0, y0)
    fx1, fy1 = min(W, x0 + w), min(H, y0 + h)
    if fx1 <= fx0 or fy1 <= fy0 or alpha <= 0:
        return
    sub = img[fy0 - y0: fy1 - y0, fx0 - x0: fx1 - x0]
    a = sub[..., 3:4].astype(np.float32) * (alpha / 255.0)
    roi = frame[fy0:fy1, fx0:fx1].astype(np.float32)
    frame[fy0:fy1, fx0:fx1] = (roi * (1 - a) + sub[..., :3].astype(np.float32) * a).astype(np.uint8)


