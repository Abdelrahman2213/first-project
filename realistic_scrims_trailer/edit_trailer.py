def section_at(t):
    if t < 3.0:
        return "hook"
    if t < 9.0:
        return "intro"
    if 16.5 <= t < 17.5:
        return "break"
    if t < 21.0:
        return "drop"
    if t < 25.0:
        return "tension"
    if t < 27.5:
        return "climax"
    if t < 29.0:
        return "breathe"
    if t < 31.0:
        return "climax"
    if t < 36.0:
        return "end"
    return "tail"


def build_score():
    n = int(TOTAL * SR)
    drums = np.zeros((n, 2))
    bass = np.zeros((n, 2))
    melo = np.zeros((n, 2))
    padb = np.zeros((n, 2))
    sfx = np.zeros((n, 2))

    K = {"hook": [], "intro": [0, 8, 11], "drop": [0, 6, 10], "tension": [0, 8],
         "climax": [0, 3, 6, 10, 11, 14], "breathe": [], "end": [0, 8, 10], "break": [], "tail": []}
    C = {"intro": [12], "drop": [4, 12], "tension": [4, 12], "climax": [4, 12], "end": [12]}
    HAT = {"hook": 4, "intro": 2, "drop": 1, "tension": 2, "climax": 1, "breathe": 4, "end": 2}

    # grid: bars start on odd seconds (1, 3, 5 ...); steps every 16th from t=0
    nsteps = int(TOTAL / STEP)
    for s in range(nsteps):
        t = s * STEP
        sec = section_at(t)
        bar_step = int(round((t - 1.0) / STEP)) % 16
        bar_idx = int((t - 1.0) // 2.0) if t >= 1.0 else -1
        if sec == "tail":
            continue
        if bar_step in K.get(sec, []):
            add(drums, kick(1.2 if sec == "climax" else 1.0), t, 0.95)
        if bar_step in C.get(sec, []):
            add(drums, clap(), t, 0.55 if sec != "end" else 0.4)
        hs = HAT.get(sec)
        if hs and bar_step % hs == 0:
            vel = 0.55 if bar_step % 4 == 0 else 0.35
            add(drums, hat(), t, vel * (0.6 if sec in ("hook", "breathe") else 1.0), pan=0.25)
        if sec in ("drop", "climax") and bar_idx % 2 == 1 and bar_step in (13, 14, 15):
            for k in range(2):  # 32nd-note hat roll
                add(drums, hat(), t + k * STEP / 2, 0.3, pan=-0.2)
        if sec in ("drop", "climax", "intro") and bar_step == 14:
            add(drums, hat(True), t, 0.25, pan=0.3)

        # 808 follows the kick in groove sections
        if sec in ("intro", "drop", "climax", "end", "tension") and bar_step in K.get(sec, [0]):
            ch = PROG[bar_idx % 4] if bar_idx >= 0 else "Am"
            root = CHORDS[ch][1]
            ks = K[sec]
            nxt = [k for k in ks if k > bar_step]
            dur = ((nxt[0] if nxt else 16) - bar_step) * STEP
            glide = root * 1.5 if (sec == "climax" and bar_step == 0) else None
            add(bass, bass808(root, dur + 0.02, glide, 3.2 if sec == "climax" else 2.6), t, 0.9)

        # phonk cowbell melody
        if sec in ("intro", "drop", "climax", "end"):
            ph_step = int(round((t - 1.0) / STEP)) % 32
            for st, m in COWBELL:
                if st == ph_step:
                    g = {"intro": 0.30, "drop": 0.42, "climax": 0.46, "end": 0.26}[sec]
                    add(melo, cowbell(m), t, g, pan=-0.15)
                    if sec == "climax":
                        add(melo, cowbell(m + 12), t, 0.16, pan=0.3)

    # pads per bar
    for b in range(-1, 18):
        t0 = 1.0 + 2 * b
        if t0 >= 36.0:
            break
        ch = PROG[b % 4] if b >= 0 else "Am"
        start = max(0.0, t0)
        dur = 2.0 if b >= 0 else 1.0
        g = 0.22 if section_at(start + 0.01) in ("hook", "tension", "breathe", "end") else 0.14
        add(padb, pad(CHORDS[ch][0], dur + 0.4), start, g)
    # hook drone
    add(padb, sos_filter(bass808(midi_hz(33), 3.0, drive=1.2), "lowpass", 300), 0.0, 0.45)
    # tension: hat 16ths accelerate + snare roll 23 -> 24.85
    t = 23.0
    while t < 24.85:
        p = (t - 23.0) / 1.85
        add(drums, clap(), t, 0.15 + 0.35 * p)
        t += STEP if p < 0.5 else (STEP / 2 if p < 0.85 else STEP / 4)
    # breathe: low 808 sustain
    add(bass, bass808(CHORDS["F"][1], 1.5, drive=1.8), 27.5, 0.6)
    # end card: final ring-out of the pad after the final hit
    add(padb, pad(CHORDS["Am"][0], 1.2), 36.0, 0.18)

    # ---- SFX ----
    for ti, s in IMPACTS:
        add(sfx, impact(s), ti, 0.55)
    for ti, d in WHIPS:
        add(sfx, whoosh(0.32, up=d > 0), ti - 0.2, 0.55, pan=0.4 * d)
    add(sfx, riser(1.5), 1.5, 0.55)            # hook -> title
    add(sfx, riser(1.5), 7.5, 0.45)            # into the drop
    add(sfx, reverse_cymbal(0.9), 16.6, 0.5)   # victory break -> back in
    add(sfx, riser(1.0), 20.0, 0.35)           # into rocket fire
    add(sfx, riser(3.85), 21.0, 0.6)           # rocket flight tension
    add(sfx, reverse_cymbal(0.7), 28.3, 0.45)  # breathe -> victory
    add(sfx, riser(1.2), 29.8, 0.3)            # into end card
    for ti in (0.12, 9.04, 11.04, 12.54, 14.5, 28.5):   # caption slams
        add(sfx, text_hit(), ti, 0.5)
    # freeze-frame "tape stop" accent
    add(sfx, whoosh(0.35, up=False), 14.5, 0.4)
    # code reveal blips
    for i in range(len(MAP_CODE)):
        add(sfx, blip(1600 + 90 * i), 31.62 + i * 0.028, 0.5, pan=-0.6 + 1.2 * i / len(MAP_CODE))

    ir = make_ir()
    drums = reverb(drums, ir, 0.10)
    melo = reverb(melo, ir, 0.22)
    padb = reverb(padb, ir, 0.30)
    sfx = reverb(sfx, ir, 0.18)
    bass = sos_filter(bass, "highpass", 28)  # control the sub
    music = drums * 0.9 + bass * 0.75 + melo * 0.85 + padb * 0.9
    # silence gaps for punch: 2.92-3.0 and 24.85-25.0
    for a, b in ((2.92, 3.0), (24.85, 25.0)):
        i0, i1 = int(a * SR), int(b * SR)
        music[i0:i1] *= np.linspace(1, 0, i1 - i0)[:, None] ** 3
    # fade the groove out into the final hit
    i36 = int(36.0 * SR)
    music[i36:] *= np.linspace(1, 0, len(music) - i36)[:, None] ** 2
    return music, sfx


