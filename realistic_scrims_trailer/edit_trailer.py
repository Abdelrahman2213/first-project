RNG = np.random.default_rng(1234)


def kick(big=1.0):
    t = t_arr(0.55)
    f = 45 + 110 * np.exp(-t / 0.035)
    ph = 2 * np.pi * np.cumsum(f) / SR
    x = np.sin(ph) * np.exp(-t / (0.22 * big))
    click = RNG.standard_normal(len(t)) * np.exp(-t / 0.003) * 0.3
    return np.tanh(1.8 * (x + click)) * 0.9


def clap():
    t = t_arr(0.35)
    n = RNG.standard_normal(len(t))
    e = np.zeros(len(t))
    for d in (0.0, 0.011, 0.022):
        e += (t >= d) * np.exp(-np.clip(t - d, 0, None) / 0.012)
    e += np.exp(-t / 0.09) * 0.6
    x = sos_filter(n * e, "bandpass", [900, 6000])
    tone = np.sin(2 * np.pi * 190 * t) * np.exp(-t / 0.04) * 0.4
    return (x * 1.6 + tone) * 0.8


def hat(open_=False):
    t = t_arr(0.25 if open_ else 0.06)
    n = RNG.standard_normal(len(t))
    x = sos_filter(n, "highpass", 7500)
    return x * np.exp(-t / (0.07 if open_ else 0.012)) * 0.35


def cowbell(m, dur=0.22):
    t = t_arr(dur)
    f = midi_hz(m)
    x = signal.square(2 * np.pi * f * t, 0.5) * 0.6 + signal.square(2 * np.pi * f * 1.4829 * t, 0.5) * 0.4
    x = sos_filter(x, "bandpass", [f * 0.9, min(f * 4.5, 15000)])
    return x * np.exp(-t / 0.085) * 0.55


def bass808(f, dur, glide_from=None, drive=2.6):
    t = t_arr(dur)
    if glide_from:
        fr = f + (glide_from - f) * np.exp(-t / 0.06)
    else:
        fr = np.full(len(t), f)
    ph = 2 * np.pi * np.cumsum(fr) / SR
    x = np.sin(ph) * env_ar(len(t), 0.003, min(0.08, dur * 0.4)) * np.exp(-t / 1.4)
    return np.tanh(drive * x) / np.tanh(drive) * 0.8


def pad(chord, dur):
    t = t_arr(dur)
    x = np.zeros(len(t))
    for m in chord:
        for det in (-0.12, 0.0, 0.13):
            f = midi_hz(m + det)
            x += signal.sawtooth(2 * np.pi * f * t + RNG.uniform(0, 6.28))
    x = sos_filter(x, "lowpass", 1100) / (len(chord) * 3)
    return x * env_ar(len(t), 0.25, 0.4)


def riser(dur, f0=200, f1=2400):
    t = t_arr(dur)
    p = t / dur
    n = RNG.standard_normal((len(t), 2))
    out = np.zeros_like(n)
    hop = 2048
    for i in range(0, len(t), hop):          # time-varying bandpass in blocks
        fc = f0 * (f1 / f0) ** p[i]
        seg = n[max(0, i - 512): i + hop]
        y = sos_filter(seg, "bandpass", [fc * 0.6, min(fc * 1.8, 20000)])
        out[i: i + hop] = y[-len(out[i: i + hop]):]
    tone_f = 110 * 2 ** (3 * p)
    tone = np.sin(2 * np.pi * np.cumsum(tone_f) / SR) * 0.25
    e = p ** 2.2
    return (out * 0.9 + tone[:, None]) * e[:, None] * 0.7


def reverse_cymbal(dur):
    t = t_arr(dur)
    n = sos_filter(RNG.standard_normal((len(t), 2)), "highpass", 4000)
    return n * ((t / dur) ** 3)[:, None] * 0.45


def whoosh(dur=0.35, up=True):
    t = t_arr(dur)
    p = t / dur
    n = RNG.standard_normal((len(t), 2))
    out = np.zeros_like(n)
    hop = 1024
    for i in range(0, len(t), hop):
        q = p[i] if up else 1 - p[i]
        fc = 300 * (12 ** q)
        seg = n[max(0, i - 512): i + hop]
        y = sos_filter(seg, "bandpass", [fc * 0.5, min(fc * 2.0, 20000)])
        out[i: i + hop] = y[-len(out[i: i + hop]):]
    e = np.sin(np.pi * p) ** 1.5
    return out * e[:, None] * 0.8


def impact(strength=1.0):
    t = t_arr(2.4)
    f = 32 + 60 * np.exp(-t / 0.08)
    sub = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.7)
    crack = sos_filter(RNG.standard_normal(len(t)), "lowpass", 5000) * np.exp(-t / 0.05)
    metal = sum(np.sin(2 * np.pi * fr * t) * np.exp(-t / d) for fr, d in
                ((313, 0.5), (487, 0.35), (811, 0.25), (1273, 0.18))) * 0.12
    x = np.tanh(1.5 * (sub * 1.0 + crack * 0.7 + metal)) * 0.9
    return x * strength


def text_hit():
    t = t_arr(0.18)
    n = sos_filter(RNG.standard_normal(len(t)), "bandpass", [1500, 9000]) * np.exp(-t / 0.02)
    thump = np.sin(2 * np.pi * (70 + 120 * np.exp(-t / 0.02)) * t) * np.exp(-t / 0.06)
    return (n * 0.5 + thump * 0.6) * 0.6


def blip(f=1800):
    t = t_arr(0.05)
    return np.sin(2 * np.pi * f * t) * np.exp(-t / 0.012) * 0.25


