def load_src_audio(path):
    raw = run(["ffmpeg", "-v", "error", "-i", path, "-vn", "-ac", "2", "-ar", str(SR),
               "-f", "f32le", "-"], capture_output=True).stdout
    return np.frombuffer(raw, np.float32).reshape(-1, 2).astype(np.float64)


def seg_map(seg, t):
    ks = seg["keys"]
    return np.interp(t, [k[0] for k in ks], [k[1] for k in ks])


def game_audio(srcs):
    out = np.zeros((int(TOTAL * SR), 2))
    for seg in SEGMENTS:
        if seg.get("endcard"):
            continue
        a0, a1 = seg["keys"][0][0], seg["keys"][-1][0]
        i0, i1 = int(a0 * SR), int(a1 * SR)
        t = np.arange(i0, i1) / SR
        st = seg_map(seg, t)
        src = srcs[seg["src"]]
        idx = st * SR
        y = np.stack([np.interp(idx, np.arange(len(src)), src[:, c]) for c in range(2)], 1)
        # gain: inside narration-free windows only, muted on freeze frames
        g = np.zeros(len(t))
        for w0, w1 in GAME_AUDIO_WINDOWS[seg["src"]]:
            g = np.maximum(g, np.clip(np.minimum(st - w0, w1 - st) / 0.06, 0, 1))
        rate = np.gradient(st) * SR
        g *= np.clip(rate / 0.3, 0, 1)
        n = len(t)
        f = min(int(0.012 * SR), n // 2)
        g[:f] *= np.linspace(0, 1, f)
        g[-f:] *= np.linspace(1, 0, f)
        out[i0:i1] += y * g[:, None]
    return out


def envelope(x, att=0.03, rel=0.3):
    lvl = np.abs(x).max(1) if x.ndim == 2 else np.abs(x)
    ea, er = math.exp(-1 / (att * SR)), math.exp(-1 / (rel * SR))
    env = np.zeros_like(lvl)
    e = 0.0
    # decimated follower for speed
    hop = 64
    for i in range(0, len(lvl), hop):
        v = lvl[i:i + hop].max()
        c = ea ** hop if v > e else er ** hop
        e = c * e + (1 - c) * v
        env[i:i + hop] = e
    return env


def ffmpeg_write_wav(x, path, codec="pcm_s24le"):
    x = np.ascontiguousarray(x.astype(np.float32))
    run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", str(x.shape[1] if x.ndim == 2 else 1),
         "-i", "-", "-c:a", codec, path], input=x.tobytes())


def build_audio(args, work, out_dir):
    log("[audio] voice-over")
    vo, placed = synth_vo(args.voices, work)
    log("[audio] score + sfx")
    music, sfx = build_score()
    log("[audio] gameplay audio")
    srcs = {"sc": load_src_audio(args.scrims), "t1": load_src_audio(args.timeline)}
    game = game_audio(srcs)
    game = sos_filter(game, "highpass", 60)

    # duck music (and game audio) under narration: ~ -9 dB
    env = envelope(vo, 0.02, 0.35)
    env = env / (env.max() + 1e-9)
    duck = 1.0 - 0.75 * np.clip(env * 3.0, 0, 1)     # ~ -12 dB under narration
    duck_g = 1.0 - 0.6 * np.clip(env * 3.0, 0, 1)

    mix = music * 0.45 * duck[:, None] + sfx * 0.55 + game * 1.0 * duck_g[:, None] + vo * 1.25
    # final tail fade
    nf = int(0.35 * SR)
    mix[-nf:] *= np.linspace(1, 0, nf)[:, None] ** 2
    # soft bus clip safety before loudnorm
    mix = np.tanh(mix * 0.9) / 0.9

    ffmpeg_write_wav(vo, os.path.join(out_dir, "voiceover.wav"))
    pre = os.path.join(work, "mix_pre.wav")
    ffmpeg_write_wav(mix, pre, "pcm_f32le")
    for name, stem in (("stem_music.wav", music * 0.45 * duck[:, None]), ("stem_sfx.wav", sfx * 0.55),
                       ("stem_game.wav", game * 1.0 * duck_g[:, None]), ("stem_vo.wav", vo * 1.25)):
        ffmpeg_write_wav(stem, os.path.join(work, name), "pcm_f32le")
    ffmpeg_write_wav(sfx * 0.55, os.path.join(ASSETS, "sfx_layer.wav"), "pcm_s16le")
    ffmpeg_write_wav(music * 0.45, os.path.join(ASSETS, "music_original_instrumental.wav"), "pcm_s16le")

    # two-pass loudnorm -> -14 LUFS, -1.5 dBTP
    r = subprocess.run(["ffmpeg", "-hide_banner", "-i", pre, "-af",
                        "loudnorm=I=-14:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True)
    js = json.loads(r.stderr[r.stderr.rfind("{"): r.stderr.rfind("}") + 1])
    af = ("loudnorm=I=-14:TP=-1.5:LRA=11:linear=true:"
          f"measured_I={js['input_i']}:measured_TP={js['input_tp']}:measured_LRA={js['input_lra']}:"
          f"measured_thresh={js['input_thresh']}:offset={js['target_offset']},"
          "alimiter=limit=0.84:attack=3:release=40:level=false")
    final = os.path.join(out_dir, "final_audio.wav")
    run(["ffmpeg", "-v", "error", "-y", "-i", pre, "-af", af, "-ar", str(SR), "-c:a", "pcm_s24le", final])
    with open(os.path.join(work, "vo_placement.json"), "w") as f:
        json.dump(placed, f, indent=1)
    return final, placed


