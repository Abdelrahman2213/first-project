def suck(dur=0.35):
    """Reverse 'inhale' into a hit."""
    t = t_arr(dur)
    p = t / dur
    x = sos_filter(RNG.standard_normal((len(t), 2)), "bandpass", [400, 7000])
    sub = np.sin(2 * np.pi * np.cumsum(30 + 60 * p) / SR)[:, None] * 0.5
    return (x * 0.6 + sub) * (p ** 3)[:, None] * 0.8


def launch_blast():
    a = impact(1.0)
    w = band_sweep(1.4, 3500, 250, lambda p: (1 - p) ** 1.5 * np.minimum(p / 0.02, 1))
    x = np.zeros((max(len(a), len(w)), 2))
    x[:len(a)] += a[:, None]
    x[:len(w)] += w * 0.9
    return x


def engine_roar(dur):
    n = int(dur * SR)
    p = np.arange(n) / n
    w = band_sweep(dur, 260, 900, lambda p: 0.25 + 0.75 * p ** 1.5, width=(0.5, 2.5))
    rum = sos_filter(RNG.standard_normal(n), "lowpass", 90)
    rum = rum / np.abs(rum).max() * (0.3 + 0.7 * p)
    return w * 0.6 + rum[:, None] * 0.5


def ambience_bed():
    """Non-musical air/rumble bed so the cut never drops into dead silence."""
    n = int(TOTAL * SR)
    t = np.arange(n) / SR
    w = np.cumsum(RNG.standard_normal((n, 2)), 0)
    w = sos_filter(sos_filter(w, "highpass", 25), "lowpass", 420)
    w /= np.abs(w).max()
    rum = sos_filter(RNG.standard_normal((n, 2)), "lowpass", 70)
    rum /= np.abs(rum).max()
    mod = (0.65 + 0.35 * np.sin(2 * np.pi * 0.11 * t) * np.sin(2 * np.pi * 0.037 * t + 1))[:, None]
    bed = w * mod + rum * 0.6
    bed *= 0.05 / np.sqrt((bed ** 2).mean())
    keys = [(0, 0.5), (2.9, 0.8), (3.0, 0.35), (8.9, 0.4), (9.0, 0.65), (17.5, 0.7), (20.8, 0.85), (21.0, 0.6), (24.8, 1.0),
            (24.85, 0.0), (25.0, 0.0), (25.05, 0.7), (27.5, 0.6), (28.0, 0.85), (29, 0.45),
            (31, 0.5), (36, 0.45), (TOTAL, 0.0)]
    g = np.interp(t, [k[0] for k in keys], [k[1] for k in keys])
    return bed * g[:, None]


def build_sound_design():
    n = int(TOTAL * SR)
    fx = np.zeros((n, 2))

    def A(x, t0, g=1.0, pan=0.0):
        add(fx, x, t0, g, pan)

    for ti, s in IMPACTS:
        A(impact(s), ti, 0.6)
    # HOOK: shot -> kill confirm -> heartbeat -> inhale into the title
    A(text_hit(), 0.12, 0.55)
    A(hit_confirm(), 1.04, 0.55)
    A(heartbeat(0.8), 1.62)
    A(heartbeat(0.9), 2.25)
    A(riser(1.4), 1.55, 0.5)
    A(suck(0.3), 2.65, 0.7)
    # TITLE: braam + digital spawn-in
