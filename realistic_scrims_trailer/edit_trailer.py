def blit_rgba(dst, src):
    """alpha-composite src (BGRA) centred onto dst (BGRA), in place."""
    h, w = src.shape[:2]
    H2, W2 = dst.shape[:2]
    y0, x0 = (H2 - h) // 2, (W2 - w) // 2
    ys, xs = max(0, -y0), max(0, -x0)
    y0c, x0c = max(0, y0), max(0, x0)
    sub = src[ys: ys + min(h, H2), xs: xs + min(w, W2)]
    hh, ww = sub.shape[:2]
    hh, ww = min(hh, H2 - y0c), min(ww, W2 - x0c)
    sub = sub[:hh, :ww].astype(np.float32)
    d = dst[y0c:y0c + hh, x0c:x0c + ww].astype(np.float32)
    a = sub[..., 3:4] / 255
    rgb = sub[..., :3] * a + d[..., :3] * (1 - a)
    al = sub[..., 3:4] + d[..., 3:4] * (1 - a)
    dst[y0c:y0c + hh, x0c:x0c + ww] = np.concatenate([rgb, al], 2).astype(np.uint8)


