class SegmentFrames:
    def __init__(self, path, t_lo, t_hi):
        ss = max(0.0, math.floor(t_lo * FPS - 2) / FPS)
        dur = (t_hi - ss) + 3 / FPS
        raw = run(["ffmpeg", "-v", "error", "-ss", f"{ss:.4f}", "-i", path, "-t", f"{dur:.4f}",
                   "-vf", "scale=in_color_matrix=bt709:in_range=tv:out_range=pc,format=bgr24",
                   "-f", "rawvideo", "-pix_fmt", "bgr24", "-"], capture_output=True).stdout
        self.frames = np.frombuffer(raw, np.uint8).reshape(-1, H, W, 3)
        self.first = int(math.ceil(ss * FPS - 1e-6))

    def get(self, t_src, blend):
        f = t_src * FPS - self.first
        n = len(self.frames)
        i0 = int(math.floor(f))
        frac = f - i0
        i0 = min(max(i0, 0), n - 1)
        if not blend or frac < 0.08 or i0 + 1 >= n:
            j = min(max(int(round(f)), 0), n - 1)
            return self.frames[j].copy()
        return cv2.addWeighted(self.frames[i0], 1 - frac, self.frames[i0 + 1], frac, 0)


def make_grade_lut():
    x = np.arange(256) / 255.0
    s = x * x * (3 - 2 * x)
    base = x * 0.62 + s * 0.38                      # contrast
    sh = (1 - x) ** 2.2
    b = np.clip(base + 0.035 * sh, 0, 1)            # cool shadows
    g = np.clip(base + 0.008 * sh, 0, 1)
    r = np.clip(base - 0.025 * sh, 0, 1)
    return [(c * 255).astype(np.uint8) for c in (b, g, r)]


def make_vignette(strength=0.30):
    yy, xx = np.mgrid[0:H, 0:W]
    d = np.sqrt(((xx - W / 2) / (W / 2)) ** 2 * 0.8 + ((yy - H / 2) / (H / 2)) ** 2)
    v = 1 - strength * np.clip(d - 0.45, 0, None) ** 1.6
    v = np.clip(v, 0, 1)
    return np.repeat((v * 255).astype(np.uint8)[..., None], 3, 2)


def decay(t, t0, dur):
    if t < t0 or t >= t0 + dur:
        return 0.0
    return math.exp(-4.5 * (t - t0) / dur)


def radial_blur(frame, amount, taps=5):
    acc = frame.astype(np.float32)
    for i in range(1, taps + 1):
        M = cv2.getRotationMatrix2D((W / 2, H / 2), 0, 1 + amount * i / taps)
        acc += cv2.warpAffine(frame, M, (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT101)
    return (acc / (taps + 1)).astype(np.uint8)


def shake_xy(t, amp):
    return (amp * (math.sin(t * 91.3) * 0.6 + math.sin(t * 57.1 + 1.3) * 0.4),
            amp * (math.sin(t * 77.7 + 0.7) * 0.6 + math.sin(t * 43.9 + 2.1) * 0.4))


def render_video(args, work, out_video, stills=None):
    lut = make_grade_lut()
    vig = make_vignette()
    overlays, saved = build_overlays()
    gfx_dir = os.path.join(ASSETS, "graphics")
    os.makedirs(gfx_dir, exist_ok=True)
    for k, im in saved.items():
        cv2.imwrite(os.path.join(gfx_dir, f"{k}.png"), im)

    paths = {"sc": args.scrims, "t1": args.timeline}
    code_times, code_end = CODE_GROUP_TIMES, CODE_GROUP_END
    vp = os.path.join(work, "vo_placement.json")
    if os.path.exists(vp):
        with open(vp) as f:
            placed = json.load(f)
        code_times = [p["start"] for p in placed[-3:]]
        code_end = placed[-1]["end"] + 0.25
    cut_times = sorted({s["keys"][0][0] for s in SEGMENTS})
    impact_t = {t for t, _ in IMPACTS}

    enc = None
    if stills is None:
        enc = subprocess.Popen([
            "ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{W}x{H}",
            "-r", str(FPS), "-i", "-",
            "-vf", "scale=in_range=pc:out_color_matrix=bt709:out_range=tv,format=yuv420p",
            "-c:v", "libx264", "-preset", "slow", "-crf", "18", "-maxrate", "16M", "-bufsize", "32M",
            "-profile:v", "high", "-level", "4.2", "-g", "60", "-bf", "2",
            "-color_primaries", "bt709", "-color_trc", "bt709", "-colorspace", "bt709", "-color_range", "tv",
            "-movflags", "+faststart", out_video], stdin=subprocess.PIPE)

    nframes = int(round(TOTAL * FPS))
    frames_wanted = None
    if stills is not None:
        frames_wanted = {int(round(s * FPS)): s for s in stills}
    cache = {}
    for n in range(nframes):
        t = n / FPS
        if frames_wanted is not None and n not in frames_wanted:
            continue
        si = max(i for i, s in enumerate(SEGMENTS) if s["keys"][0][0] <= t + 1e-9)
        seg = SEGMENTS[si]
        if si not in cache:
            cache.clear()
            ks = seg["keys"]
            cache[si] = SegmentFrames(paths[seg["src"]], min(k[1] for k in ks), max(k[1] for k in ks))
        st = float(seg_map(seg, t))
        st_next = float(seg_map(seg, t + 1 / FPS))
        rate = (st_next - st) * FPS
        frame = cache[si].get(st, blend=(0.05 < rate < 0.92))
        seg_t0, seg_t1 = seg["keys"][0][0], seg["keys"][-1][0]
        u = (t - seg_t0) / (seg_t1 - seg_t0)

        # ---- camera: zoom / punch / shake / rotation ----
        z = seg.get("zoom", 1.0) * (1.0 + 0.035 * u)     # slow push-in per shot
        amp = 0.0
        rot = 0.0
        for ti, s in IMPACTS:
            k = decay(t, ti, 0.4)
            z += 0.09 * s * k
            amp += 16 * s * decay(t, ti, 0.32)
            rot += 0.6 * s * decay(t, ti, 0.3) * math.sin(t * 60)
        for ct in cut_times:
            if ct not in impact_t:
                z += 0.045 * decay(t, ct, 0.22)
        for a0, a1 in BEAT_BUMP_RANGES:
            if a0 <= t < a1:
                ph = ((t - a0) % BEAT)
                z += 0.014 * math.exp(-ph / 0.07)
        if seg.get("endcard"):
            z = 1.06 + 0.05 * u
        dx, dy = shake_xy(t, amp)
        z = max(z, 1.0 + 2 * (abs(dx) + abs(dy)) / W + 0.004)
        M = cv2.getRotationMatrix2D((W / 2, H / 2), rot, z)
        M[0, 2] += dx
        M[1, 2] += dy
        frame = cv2.warpAffine(frame, M, (W, H), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT101)
        for ti, s_ in RADIAL_HITS:
            k = decay(t, ti, 0.14)
            if k > 0.05:
                frame = radial_blur(frame, 0.09 * s_ * k)

        # ---- whip transitions: directional motion blur around cuts ----
        for wt, d in WHIPS:
            dt = t - wt
            if -0.05 <= dt < 0.05:
                k = 1 - abs(dt + 0.5 / FPS) / 0.05
                L = int(10 + 110 * max(k, 0))
                ker = np.zeros((1, L), np.float32)
                ker[0, :] = 1.0 / L
                frame = cv2.filter2D(frame, -1, ker)
                shift = int(d * 70 * max(k, 0) * (1 if dt < 0 else -1))
                frame = np.roll(frame, shift, axis=1)

        # ---- grade ----
        b, g, r = cv2.split(frame)
        frame = cv2.merge([cv2.LUT(b, lut[0]), cv2.LUT(g, lut[1]), cv2.LUT(r, lut[2])])
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        gray3 = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
        sat = 1.12
        if seg.get("freeze") and seg["freeze"][0] <= t < seg["freeze"][1]:
            sat = 0.55
        frame = cv2.addWeighted(frame, sat, gray3, 1 - sat, 0)
        if seg.get("freeze") and seg["freeze"][0] <= t < seg["freeze"][1]:
            tint = np.full_like(frame, CYAN_BGR)
            frame = cv2.addWeighted(frame, 0.86, tint, 0.14, 0)

        if not seg.get("endcard"):  # gentle unsharp mask for crisper detail on phones
            soft = cv2.GaussianBlur(frame, (0, 0), 1.3)
            frame = cv2.addWeighted(frame, 1.4, soft, -0.4, 0)

        # ---- section looks ----
        if "dim" in seg:
            k = min((t - seg_t0) / 0.25, 1.0) * min((seg_t1 - t) / 0.2, 1.0)
            if seg.get("blur"):  # soften busy background under the title
                small = cv2.resize(frame, (W // 3, H // 3), interpolation=cv2.INTER_AREA)
                soft = cv2.resize(cv2.GaussianBlur(small, (0, 0), 3), (W, H), interpolation=cv2.INTER_LINEAR)
                frame = cv2.addWeighted(frame, 1 - 0.85 * k, soft, 0.85 * k, 0)
            frame = cv2.convertScaleAbs(frame, alpha=1 - (1 - seg["dim"]) * k)
        if seg.get("endcard"):
            small = cv2.resize(frame, (W // 4, H // 4), interpolation=cv2.INTER_AREA)
            small = cv2.GaussianBlur(small, (0, 0), 5)
            frame = cv2.resize(small, (W, H), interpolation=cv2.INTER_LINEAR)
            frame = cv2.convertScaleAbs(frame, alpha=0.42)
            # cyan radial glow behind the code
            if "glow" not in cache:
                yy, xx = np.mgrid[0:H, 0:W]
                gl = np.exp(-(((xx - W / 2) / 520) ** 2 + ((yy - 1140) / 300) ** 2))
                cache["glow"] = (gl[..., None] * np.array(CYAN_BGR, np.float32) * 0.22).astype(np.uint8)
            pulse = 0.75 + 0.25 * math.exp(-((t - 31.0) % BEAT) / 0.12)
            frame = cv2.add(frame, (cache["glow"] * pulse).astype(np.uint8))

        frame = cv2.multiply(frame, vig, scale=1 / 255)

        # ---- chromatic aberration on impacts ----
        ca = max([decay(t, ti, 0.14) * s for ti, s in IMPACTS if ti > 0] + [0])  # clean first frame
        if ca > 0.05:
            sh = int(10 * ca)
            b, g, r = cv2.split(frame)
            frame = cv2.merge([np.roll(b, -sh, 1), g, np.roll(r, sh, 1)])

        # ---- overlays ----
        for o in overlays:
            o.draw(frame, t)
        # code-group highlight under each group as the VO reads it
        if t >= code_times[0] - 0.05 and t < code_end:
            gi = max(i for i, gt in enumerate(code_times) if t >= gt - 0.05)
            centers = [W / 2 - 300, W / 2, W / 2 + 300]
            x0 = int(centers[gi] - 120)
            g0 = max(code_times[gi] - 0.05, 31.95)  # wait until the digits have wiped in
            if t < g0:
                k = 0.0
            else:
                k = min((t - g0) / 0.12, 1.0)
            if k > 0:
                cv2.rectangle(frame, (x0, 1212), (x0 + int(240 * k), 1220), CYAN_BGR, -1)

        # ---- flashes ----
        fl = max([decay(t, ti, 0.16) * s for ti, s in IMPACTS if ti > 0] + [0])
        if fl > 0.02:
            col = np.full_like(frame, 255)
            col[..., 0] = 255
            col[..., 1] = 245
            col[..., 2] = 225
            frame = cv2.addWeighted(frame, 1 - 0.55 * min(fl, 1), col, 0.55 * min(fl, 1), 0)
        # cut-to-black at the very end
        if t > TOTAL - 0.3:
            frame = cv2.convertScaleAbs(frame, alpha=max(0.0, (TOTAL - t) / 0.3))

        if enc:
            enc.stdin.write(frame.tobytes())
        else:
            cv2.imwrite(os.path.join(work, f"still_{t:06.2f}.png"), frame)
        if n % 120 == 0:
            log(f"  frame {n}/{nframes}  t={t:5.2f}  [{seg['name']}]")
    if enc:
        enc.stdin.close()
        if enc.wait() != 0:
            raise SystemExit("encoder failed")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scrims", required=True, help='"fortnite new video scrims.mp4"')
    ap.add_argument("--timeline", required=True, help='"Timeline 1.mp4"')
    ap.add_argument("--voices", required=True, help="dir containing en_US-joe-medium.onnx(+.json)")
    ap.add_argument("--out", default=HERE)
    ap.add_argument("--work", required=True, help="temp dir for intermediates")
    ap.add_argument("--stills", default=None, help="comma list of times: only render PNG stills")
    ap.add_argument("--audio-only", action="store_true")
    args = ap.parse_args()
    os.makedirs(args.work, exist_ok=True)
    os.makedirs(args.out, exist_ok=True)

    if args.stills:
        render_video(args, args.work, None, [float(s) for s in args.stills.split(",")])
        return
    final_audio, placed = build_audio(args, args.work, args.out)
    if args.audio_only:
        return
    vid = os.path.join(args.work, "video_only.mp4")
    log("[video] rendering")
    render_video(args, args.work, vid)
    out = os.path.join(args.out, "realistic_scrims_trailer.mp4")
    log("[mux]")
    run(["ffmpeg", "-v", "error", "-y", "-i", vid, "-i", final_audio, "-map", "0:v:0", "-map", "1:a:0",
         "-c:v", "copy", "-c:a", "aac", "-b:a", "256k", "-ar", str(SR), "-ac", "2",
         "-movflags", "+faststart", "-shortest", out])
    log("done:", out)


if __name__ == "__main__":
    main()
